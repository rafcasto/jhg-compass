// Builds the member's career-ops config/profile.yml from what Compass already
// knows (Profile + Goal + the CareerOps setup doc) so nobody fills in a YAML
// file by hand. Pure — tested.
//
// Key order and field names mirror career-ops' own config/profile.example.yml
// (career-ops-hq/career-ops), because the Pi worker parses this file with
// careerops-worker/lib/profile.js → parseProfile(), which reads:
//
//   candidate.full_name · email · phone · location · linkedin · github
//            · portfolio_url
//   target_roles.primary[]
//   compensation.target_range · minimum
//   location.country
//
// …and hands them to the generated CV PDF header (jobs/pdf.js), the
// cover-letter contact block (jobs/cover.js) and the application-form autofill
// (jobs/apply_form.js, jobs/apply_fill.js). Every one of those was reading a
// field this builder never emitted.
//
// Optional keys are OMITTED when blank rather than written as "". parseProfile
// normalises missing to "", so an absent key and an empty one behave
// identically downstream — but the file stays readable, and `minimum: ""` used
// to look like a deliberate "no walk-away number" when it only meant "never
// asked".
import type { Profile } from "@/lib/types";
import type { Goal } from "@/lib/goal";
import type { CareerOpsContact, CareerOpsPolicy } from "./types";

const q = (v: unknown) => JSON.stringify(String(v ?? "").trim()); // JSON strings are valid YAML scalars
const clean = (v: unknown) => String(v ?? "").trim();

/** `key: value`, or nothing at all when the value is blank. */
const opt = (indent: string, key: string, v: unknown): string[] =>
  clean(v) ? [`${indent}${key}: ${q(v)}`] : [];

export interface ProfileYamlInput {
  profile: Pick<Profile, "email" | "firstName" | "lastName" | "country"> | null | undefined;
  goal: Goal | null | undefined;
  /** Optional extra lines the member adds in Setup (e.g. visa, remote preference). */
  notes?: string;
  /** candidate.* extras — see CareerOpsContact. */
  contact?: CareerOpsContact | null;
  /** compensation.* / location.* extras — see CareerOpsPolicy. */
  policy?: CareerOpsPolicy | null;
}

export function buildProfileYaml({ profile, goal, notes, contact, policy }: ProfileYamlInput): string {
  const name = [profile?.firstName, profile?.lastName].filter(Boolean).join(" ").trim();
  const role = goal?.role?.trim() ?? "";

  // Countries where work authorization is already held. An explicit list wins;
  // otherwise the member's own country is the one safe assumption.
  const authorizedIn = (policy?.authorizedIn ?? [])
    .map(clean)
    .filter(Boolean);
  const authorized = authorizedIn.length ? authorizedIn : [clean(profile?.country)].filter(Boolean);

  const lines = [
    "# Generated by JobHacker Compass from your Profile and Compass goal.",
    "# Edit your goal on the Compass tab — this file follows it.",
    "candidate:",
    `  full_name: ${q(name)}`,
    ...opt("  ", "title", contact?.title),
    `  email: ${q(profile?.email)}`,
    ...opt("  ", "phone", contact?.phone),
    `  location: ${q(goal?.city || profile?.country)}`,
    ...opt("  ", "linkedin", contact?.linkedin),
    ...opt("  ", "portfolio_url", contact?.portfolio),
    ...opt("  ", "github", contact?.github),
    "target_roles:",
    "  primary:",
    ...(role ? [`    - ${q(role)}`] : ["    []"]),
    "  archetypes:",
    ...(role ? [`    - name: ${q(role)}`, `      level: ${q(seniority(role))}`, "      fit: \"primary\""] : ["    []"]),
    "narrative:",
    `  headline: ${q(role ? `${role}${goal?.subsector ? ` in ${goal.subsector}` : ""}` : "")}`,
    "compensation:",
    `  target_range: ${q(goal?.salary)}`,
    ...opt("  ", "minimum", policy?.minimumSalary),
    ...opt("  ", "location_flexibility", policy?.locationFlexibility),
    "location:",
    `  country: ${q(profile?.country)}`,
    `  city: ${q(goal?.city)}`,
    ...opt("  ", "visa_status", policy?.visaStatus),
    // Only written when true: career-ops treats an absent key as false, and a
    // spurious `needs_sponsorship: false` would read as a checked fact.
    ...(policy?.needsSponsorship === true ? ["  needs_sponsorship: true"] : []),
    ...(authorized.length ? ["  authorized_in:", ...authorized.map((c) => `    - ${q(c)}`)] : []),
    "preferences:",
    `  industry: ${q(goal?.subsector)}`,
    `  company_type: ${q(goal?.companyType)}`,
  ];

  const extra = (notes ?? "").trim();
  if (extra) lines.push("notes: |", ...extra.split("\n").map((l) => `  ${l}`));
  return lines.join("\n") + "\n";
}

// "Senior Product Owner" → "Senior"; "Head of Data" → "Head"; else "".
export function seniority(role: string): string {
  const m = role.match(/^(intern|junior|graduate|mid|senior|staff|principal|lead|head|director|vp|chief)\b/i);
  return m ? m[1][0].toUpperCase() + m[1].slice(1).toLowerCase() : "";
}
